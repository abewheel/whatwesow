/** Inline SVG for a speaker's portrait; decorative, so the caller labels the speaker. */
export function portraitSvg(id: string): string {
  const portrait = portraits[id];
  if (!portrait)
    return `<svg viewBox="0 0 24 24" aria-hidden="true"><rect width="24" height="24" fill="#d9c9a6"/></svg>`;
  let rects = `<rect width="24" height="24" fill="${portrait.backdrop}"/>`;
  portrait.rows.forEach((row, y) =>
    [...row].forEach((key, x) => {
      const fill = portrait.palette[key];
      if (fill)
        rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${fill}"/>`;
    }),
  );
  return `<svg viewBox="0 0 24 24" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}

export const portraitIds = Object.keys(portraits);
export const portraitRows = (id: string) => portraits[id]?.rows;
